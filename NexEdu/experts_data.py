# 专家 id → 该专家默认可用的技能 id（注入提示词，便于模型知道「我能用什么」）
_EXPERT_SKILLS = {}


def bind_skills(mapping):
    """绑定「专家 → 技能 id 列表」，由 skilllib 在导入时调用。"""
    _EXPERT_SKILLS.update(mapping or {})


def render_system(e):
    """把专家数据渲染为完整的 System Prompt（与手写四环专家同一叙事规范）。"""
    name = e.get("name") or e["id"]
    cn = e.get("cn") or ""
    stage = e.get("stage") or ""
    lines = []
    lines.append("你是「山海智绘·%s」，山海智绘专家矩阵中的**%s专家**，"
                 "位于「%s」环节。" % (name, cn, stage))
    lines.append("")
    lines.append("# 定位")
    lines.append(e.get("duty") or e.get("desc") or "")
    lines.append("")
    lines.append("# 核心职责")
    lines.append(e.get("desc") or "")
    skills = _EXPERT_SKILLS.get(e["id"]) or []
    if skills:
        lines.append("本环节可调用的技能（系统内置、按需自动调用，无需教师勾选）："
                     + "、".join(skills) + "。")
    lines.append("")
    lines.append("# 工作流")
    for i, step in enumerate(e.get("flow") or [], 1):
        lines.append("%d. %s；" % (i, step))
    lines.append("")
    lines.append("# 输出规范")
    outs = e.get("outputs") or []
    if outs:
        lines.append("按需输出《" + "》《".join(outs) + "》；")
    lines.append("使用 Markdown 结构、分点清晰；关键结论附依据或来源标注；"
                 "篇幅适中，教师可直接取整使用。")
    lines.append("")
    lines.append("# 自检要点")
    for c in e.get("check") or []:
        lines.append("- " + c)
    lines.append("")
    lines.append("# 边界")
    lines.append("你是教学专业助手，不替代教师裁定；涉及学生个人信息一律脱敏；"
                 "高危实验、敏感表述与医学/心理判断要明确提示边界并建议寻求专业支持。"
                 "所有建议须经教师确认后方可进入正式教学文件。")
    return "\n".join(lines)


def builtin_experts():
    """转换为 agents.EXPERTS 所需的字典结构（system 已渲染）。"""
    out = []
    for e in EXPERT_MATRIX:
        out.append({
            "id": e["id"],
            "name": e["name"],
            "cn": e["cn"],
            "en": e.get("en", ""),
            "stage": e.get("stage", ""),
            "desc": e.get("desc", ""),
            "outputs": list(e.get("outputs") or []),
            "system": render_system(e),
            "tags": list(e.get("tags") or []),
            "kw": list(e.get("kw") or []),
            "builtin_matrix": True,
        })
    return out


def expert_tags():
    """专家 id → 知识库检索偏好标签。"""
    return {e["id"]: list(e.get("tags") or []) for e in EXPERT_MATRIX}


def expert_keywords():
    """专家 id → 路由关键词（去重，去掉与三核心专家重复的部分）。"""
    return {e["id"]: list(e.get("kw") or []) for e in EXPERT_MATRIX
            if e.get("kw")}


def by_stage():
    """按阶段分组，供前端分组展示。"""
    groups = {}
    for e in EXPERT_MATRIX:
        groups.setdefault(e.get("stage") or "其他", []).append(e["id"])
    return groups
